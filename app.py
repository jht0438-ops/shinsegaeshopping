import streamlit as st
import pandas as pd
import plotly.express as px
st.set_page_config(page_title='신세계라이브쇼핑 경영지원 분석',layout='wide')
st.title('신세계라이브쇼핑 | 실적·운전자본 의사결정 분석')
st.caption('2023~2025 감사보고서 기반 · 금액 단위 억원 · 채널별 자료는 공시되지 않아 분석하지 않음')
df=pd.DataFrame({'연도':[2023,2024,2025], '영업수익':[2839.05254636,3283.05834277,3364.55289840], '영업비용':[2707.37376428,3106.38078400,3162.24714402], '영업이익':[131.67878208,176.67755877,202.30575438], '재고자산':[53.83442064,105.01677926,130.87079341], '매출채권및기타채권':[341.05183704,275.19828914,217.56026525], '현금및현금성자산':[1139.13270510,918.70120974,410.92767397], '기타유동금융자산':[0,0.74,500.0]})
df['영업이익률(%)']=df['영업이익']/df['영업수익']*100
df['재고/수익(%)']=df['재고자산']/df['영업수익']*100
st.sidebar.header('분석 기준')
year=st.sidebar.selectbox('기준 연도',[2025,2024,2023]); r=df[df['연도']==year].iloc[0]
a,b,c,d=st.columns(4)
a.metric('영업수익',f"{r['영업수익']:,.1f}억")
b.metric('영업이익',f"{r['영업이익']:,.1f}억")
c.metric('영업이익률',f"{r['영업이익률(%)']:.2f}%")
d.metric('재고자산',f"{r['재고자산']:,.1f}억")
tabs=st.tabs(['① 분석 배경','② 실적과 수익성','③ 재고·자금 구조','④ 개선 시나리오','⑤ 경영 제언·출처'])
with tabs[0]:
 st.subheader('왜 이 프로그램을 만들었나요?')
 st.write('2023~2025년 영업수익과 영업이익은 증가했지만 재고자산 역시 증가했습니다. 이익 성장과 재고 부담을 함께 비교하고, 재고 효율화가 자금에 미치는 영향을 시나리오로 검토합니다.')
 st.info('공개 감사보고서만으로 재고 증가의 원인, 채널별 수익성, 재고의 실제 처분 가능성을 확정할 수 없습니다. 시나리오는 의사결정 보조용 가정입니다.')
 st.dataframe(df.round(2),hide_index=True,use_container_width=True)
with tabs[1]:
 st.subheader('영업수익·영업이익 추이')
 st.plotly_chart(px.line(df,x='연도',y=['영업수익','영업이익'],markers=True),use_container_width=True)
 st.plotly_chart(px.bar(df,x='연도',y='영업이익률(%)',text_auto='.2f'),use_container_width=True)
 growth=(df.iloc[-1]['영업수익']/df.iloc[-2]['영업수익']-1)*100
 pgrowth=(df.iloc[-1]['영업이익']/df.iloc[-2]['영업이익']-1)*100
 st.write(f'2025년 전년 대비 영업수익 증가율 **{growth:.1f}%**, 영업이익 증가율 **{pgrowth:.1f}%**. 영업비용 증가율도 함께 점검해야 합니다.')
with tabs[2]:
 st.subheader('재고와 현금성 자원 변화')
 st.plotly_chart(px.line(df,x='연도',y=['재고자산','매출채권및기타채권','현금및현금성자산','기타유동금융자산'],markers=True),use_container_width=True)
 st.plotly_chart(px.bar(df,x='연도',y='재고/수익(%)',text_auto='.2f'),use_container_width=True)
 st.warning('현금및현금성자산 감소를 곧바로 유동성 악화로 해석할 수 없습니다. 2025년 기타유동금융자산 500억원을 함께 확인해야 하며, 배당·투자·영업현금흐름도 별도 검토해야 합니다.')
with tabs[3]:
 st.subheader('재고 효율화 가정 → 자금 여력')
 st.write('2025년 재고자산을 기준으로 재고 축소율과 현금 전환 가능 비율을 가정합니다. 매출·이익 영향은 자동 추정하지 않습니다.')
 reduction=st.slider('재고 축소 가정 (%)',0,40,10)
 conversion=st.slider('재고 감소분 중 현금 전환 비율 (%)',0,100,80)
 saved=130.87079341*reduction/100
 cash=saved*conversion/100
 x,y,z=st.columns(3)
 x.metric('재고 감소 가정',f'{saved:.2f}억원')
 y.metric('현금 전환 가능액 (가정)',f'{cash:.2f}억원')
 z.metric('재고 잔액 (가정)',f'{130.87079341-saved:.2f}억원')
 st.caption('단순 민감도 분석: 재고 축소가 매출손실·할인판매·반품·세금·지급조건 등에 미치는 영향은 반영하지 않았습니다.')
with tabs[4]:
 st.subheader('의사결정 제언')
 st.markdown('''**관찰:** 2023~2025년 영업이익률은 상승했지만 재고자산도 증가했습니다.\n\n**우선 확인할 항목:** 상품군별 재고회전, 장기체화 재고, 직매입/위탁판매 비중, 할인처분 손실, 매입채무 지급시점.\n\n**제언:** 전사 재고 축소를 일률적으로 추진하기보다 상품군별 마진과 재고회전을 함께 비교하여 개선 우선순위를 정하고, 회수된 자금을 어디에 배분할지 검토해야 합니다.''')
 st.subheader('자료 출처 및 한계')
 st.write('신세계라이브쇼핑 감사보고서 2024.03.29(2023년 실적), 2025.03.28(2024년 실적), 2026.03.27(2025년 실적). 포괄손익계산서와 재무상태표. 금액은 원 단위 원문을 억원으로 환산했습니다.')
 st.write('매출채권및기타채권은 순수 매출채권만을 의미하지 않습니다. 재고/수익 비율은 재고회전율이 아니며, 기간말 재고와 연간 영업수익을 단순 비교한 참고 지표입니다.')
