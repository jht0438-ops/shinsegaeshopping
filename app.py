    st.header('경영지원 관점의 결론')
    st.markdown('#### 1. 감사보고서에서 확인한 사실')
    st.markdown('- 2023~2025년 재화 판매수익은 약 **149%**, 재고자산은 약 **143%** 증가했습니다.\n- 2025년에는 재고자산 증가율이 재화 판매수익 증가율을 웃돌았고, 판매수익/평균재고 보조지표는 **2024년 11.30배 → 2025년 9.06배**로 하락했습니다.\n- 당기 재고평가손실은 **2024년 0.97억 원 → 2025년 3.29억 원**으로 증가했습니다.')
    st.markdown('#### 2. 시나리오에서 확인한 관리 목표')
    benchmark_target = float(DATA.loc[1, '판매수익/평균재고(배)'])
    scenario_gap = float(DATA.loc[2, '평균 재고자산']) - float(DATA.loc[2, '재화 판매수익']) / benchmark_target
    st.write(f'2024년의 판매수익/평균재고 비율({benchmark_target:.2f}배)을 2025년에도 적용한다고 가정하면, 2025년 재화 판매수익을 유지하면서 평균 재고를 약 {scenario_gap:.1f}억 원 낮추는 관리 목표가 계산됩니다. 이는 실현이 확정된 절감액이 아닌 가정에 따른 결과입니다.')
    st.markdown('#### 3. 해석')
    st.write('직접 판매 확대에 따라 재고 보유 규모와 평가손실 위험을 함께 점검할 필요가 있습니다. 다만 전사 공시수치만으로 재고 증가가 과잉 발주 때문인지, 신규 상품 준비 때문인지, 판매 부진 때문인지 판단할 수는 없습니다.')
    st.markdown('#### 4. 경영지원 제언')
