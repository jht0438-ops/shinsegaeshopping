with scenario:
    st.header('목표 재고 활용도 시나리오')
    st.markdown('**2025년 재화 판매수익을 유지한다는 가정**에서 평균 재고자산의 관리 목표를 계산합니다. 2024년의 판매수익/평균재고 비율을 참고 기준으로 사용합니다.')
    explain(
        '2025년에는 재화 판매수익 대비 평균 재고 활용도가 전년보다 낮아졌습니다. 과거 수준을 참고하면 관리 목표의 크기를 가늠할 수 있습니다.',
        '필요 평균 재고 = 2025년 재화 판매수익 ÷ 목표 판매수익/평균재고 비율. 현행 평균 재고와의 차이를 계산합니다.',
        '산출액은 평균 재고자산의 가상 관리 목표이지 현금 확보액이나 영업이익 개선액이 아닙니다. 목표의 실현 가능성은 상품별 수요·안전재고·발주·할인 비용 확인이 필요합니다.'
    )
    base = float(DATA.loc[2, '판매수익/평균재고(배)'])
    benchmark = float(DATA.loc[1, '판매수익/평균재고(배)'])
    target = st.slider(
        '목표 판매수익 / 평균 재고 (배)',
        min_value=8.0, max_value=13.0, value=round(benchmark, 2), step=0.05,
        help='기본값은 2024년의 실제 보조지표입니다. 경영진이 승인한 공식 목표는 아닙니다.'
    )
    sales = float(DATA.loc[2, '재화 판매수익'])
    actual_avg = float(DATA.loc[2, '평균 재고자산'])
    needed = sales / target
    difference = actual_avg - needed
    a, b, c = st.columns(3)
    a.metric('2025년 실제 평균 재고', f'{actual_avg:,.1f}억 원')
    b.metric('목표에 필요한 평균 재고', f'{needed:,.1f}억 원')
    c.metric('평균 재고 차이', f'{difference:+,.1f}억 원')
    st.caption(f'2025년 실제 활용도: {base:.2f}배 | 2024년 참고 기준: {benchmark:.2f}배')
    fig = go.Figure(go.Bar(
        x=['2025년 실제 평균 재고', '목표 기준 평균 재고'],
        y=[actual_avg, needed],
        text=[f'{actual_avg:.1f}억', f'{needed:.1f}억'],
        textposition='outside'
    ))
    fig.update_layout(title='실제 평균 재고와 목표 기준 비교', yaxis_title='억 원', height=360)
    st.plotly_chart(fig, use_container_width=True)
    if difference > 0:
        st.success(f'**시나리오 결과:** 목표 {target:.2f}배를 달성하려면 평균 재고자산을 약 {difference:,.1f}억 원 낮추는 수준의 관리가 필요합니다.')
    else:
        st.info('선택한 목표 비율에서는 현행 평균 재고보다 더 많은 평균 재고가 허용됩니다. 재고 감축 목표로 해석하지 않습니다.')
    st.warning('**해석 주의:** 판매수익/평균재고는 매출원가 기반의 정식 재고자산회전율이 아닌 보조지표입니다. 2024년 수치를 목표로 설정한 것은 분석용 가정입니다. 평균 재고 감소액은 현금 유입, 비용 절감, 이익 증가 또는 연말 재고 감축액과 같지 않습니다.')

